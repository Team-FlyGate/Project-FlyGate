"""Writes drugs_v1.txt and pairs_v1.txt from their sources (design section 6).

Drugs, in this order and deduplicated: the SIDER pilot reference set, the SignalLab presets, the CLI watchlist,
the Time Machine items, and the primary-suspect drugs of the demo cases. Pairs: the CLI watchlist and the Time
Machine items. The top-80 PTs per drug and the demo-case reactions are added by build.py, not listed here.

python -m pipeline.omics.lists [--sider <pilot_sider json.gz>]
"""
import argparse
import ast
import gzip
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SIDER = pathlib.Path("/data/hps/assoc/private/rsc/user/ybae/RSC/korea-agentic-hackathon-2026/eval/refsets/"
                     "pilot_sider_2026-09-28.json.gz")
SIGNALLAB = ROOT / "web" / "src" / "pages" / "SignalLab.tsx"
FLYGATE = ROOT / "agent" / "flygate.py"
BACKTEST = ROOT / "web" / "public" / "data" / "faers" / "backtest.json"
CASES = ROOT / "api" / "_data" / "cases.json.gz"


def _gz(path: pathlib.Path):
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        return json.load(fh)


def sider_drugs(path: pathlib.Path) -> list[str]:
    return sorted({r["drug"].upper() for r in _gz(path)["rows"]})


def presets() -> list[str]:
    body = re.search(r"const PRESETS = \[([^\]]*)\]", SIGNALLAB.read_text(encoding="utf-8")).group(1)
    return [d.upper() for d in re.findall(r"'([^']+)'", body)]


def watchlist() -> list[tuple[str, str]]:
    tree = ast.parse(FLYGATE.read_text(encoding="utf-8"))
    node = next(n for n in tree.body if isinstance(n, ast.Assign)
                and any(getattr(t, "id", None) == "DEFAULT_WATCHLIST" for t in n.targets))
    return [(d.upper(), p.lower()) for d, p in ast.literal_eval(node.value)]


def time_machine() -> list[tuple[str, str]]:
    return [(i["drug"].upper(), i["pt"].lower()) for i in json.loads(BACKTEST.read_text(encoding="utf-8"))["items"]]


def case_drugs() -> list[str]:
    return sorted({d["drug"].upper() for c in _gz(CASES) for d in c.get("drugs", []) if d.get("role") == "PS"})


def lists(sider: pathlib.Path) -> tuple[list[str], list[tuple[str, str]]]:
    wl, tm = watchlist(), time_machine()
    drugs = sider_drugs(sider) + presets() + [d for d, _ in wl] + [d for d, _ in tm] + case_drugs()
    return list(dict.fromkeys(drugs)), list(dict.fromkeys(wl + tm))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write the v1 drug and pair lists")
    ap.add_argument("--sider", type=pathlib.Path, default=SIDER)
    a = ap.parse_args(argv)
    drugs, pairs = lists(a.sider)
    head = "# generated by python -m pipeline.omics.lists; edit the sources, not this file\n"
    (HERE / "drugs_v1.txt").write_text(head + "".join(f"{d}\n" for d in drugs), encoding="utf-8")
    (HERE / "pairs_v1.txt").write_text(head + "".join(f"{d}\t{p}\n" for d, p in pairs), encoding="utf-8")
    print(f"{len(drugs)} drugs, {len(pairs)} pairs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
